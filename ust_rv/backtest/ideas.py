"""Pre-registered ideas (see IDEAS_LOG.md): curve slope factor for the 10y, and a fixed 50/50 blend of the
composite with momentum. Evaluated against the live model; nothing here changes the live model."""
import pandas as pd

from ust_rv.backtest import metrics
from ust_rv.backtest.robustness import composite_from_pressure
from ust_rv.features.zscore import rolling_z
from ust_rv.scoring.decision import hysteresis

SLOPE_ID = "F7"
SLOPE_ROW = {"name": "2s10s slope (bp)", "theme": "valuation", "sign": -1, "weight_2y": 0.0, "weight_10y": 1.0}
MOMENTUM_FACTOR = {"2y": "G2", "10y": "G1"}
BLEND_WEIGHT = 0.5


def slope_values(yields: pd.DataFrame) -> pd.Series:
    return (yields["y10"] - yields["y2"]) * 100.0


def with_slope(values: pd.DataFrame, lib: pd.DataFrame, yields: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Factor values and library with F7 added (Idea 1)."""
    v = values.assign(**{SLOPE_ID: slope_values(yields)})
    row = pd.DataFrame([SLOPE_ROW], index=[SLOPE_ID])
    return v, pd.concat([lib, row.reindex(columns=lib.columns)])


def composite(values: pd.DataFrame, lib: pd.DataFrame, theme_weights: pd.Series, tenor: str, available: set[str], zc: dict) -> pd.Series:
    z = rolling_z(values[lib.index], zc["window"], zc["min_periods"], zc["clip"])
    w = lib[f"weight_{tenor}"].astype(float).where(lambda s: s.index.isin(list(available)), 0.0)
    return composite_from_pressure(z.mul(lib["sign"].astype(float), axis=1), w, lib["theme"], theme_weights, zc)


def blend(comp: pd.Series, momentum_values: pd.Series, zc: dict) -> pd.Series:
    """Idea 2: trailing z of (0.5 x composite z + 0.5 x momentum z)."""
    mom_z = rolling_z(momentum_values, zc["window"], zc["min_periods"], zc["clip"])
    return rolling_z(BLEND_WEIGHT * comp + (1 - BLEND_WEIGHT) * mom_z, zc["window"], zc["min_periods"], zc["clip"])


def evaluate(comp: pd.Series, dy: pd.Series, y: pd.DataFrame, tenor_spec: tuple, enter: float, exit_: float,
             windows: dict[str, pd.DatetimeIndex]) -> dict:
    ycol, scol, s_years, years, _ = tenor_spec
    out = {}
    for name, idx in windows.items():
        c = comp.reindex(idx).dropna()
        rv = hysteresis(c, enter, exit_)
        yy = y.reindex(c.index)
        pnl = metrics.overlay_pnl(rv.fillna(0.0), yy[ycol], yy[scol], s_years, years, yy["ff"])
        m = metrics.summarize(rv, dy, pnl, c, n_draws=500)
        out[name] = {"ic": m["ic"], "ic_ci": m["ic_ci"], "sharpe": m["overlay_sharpe"], "sharpe_ci": m["sharpe_ci"], "hit": m["hit_rate"]}
    return out


def main() -> None:
    import logging

    from ust_rv.backtest import engine
    from ust_rv.config import factors, repo_path, settings, thresholds
    from ust_rv.panel import build_panel
    from ust_rv.scoring.scorecard import compute_scores

    logging.basicConfig(level=logging.ERROR)
    p = build_panel()
    s = compute_scores(p)
    lib = pd.DataFrame(factors()).set_index("id")
    zc = settings()["zscore"]
    available = {k for k, m in p.meta.items() if m["status"] in ("ok", "stale")}
    v_slope, lib_slope = with_slope(p.values, lib, p.yields)
    rows = []
    for T in ("2y", "10y"):
        w = engine.windows(engine.pit_share(p, T))
        wins = {"2005+": w["2005+"], "2012+": w["2005+"][w["2005+"] >= "2012-01-01"], "PIT>=90%": w["PIT>=90%"]}
        live = composite(p.values, lib, s.theme_weights[T], T, available, zc)
        assert (live - s.composite[T]).abs().max() < 1e-9, "baseline must reproduce the live composite"
        slope = composite(v_slope, lib_slope, s.theme_weights[T], T, available | {SLOPE_ID}, zc)
        mom = p.values[MOMENTUM_FACTOR[T]]
        variants = {"live": live, "idea 1: + slope": slope, "idea 2: blend": blend(live, mom, zc), "idea 3: both": blend(slope, mom, zc)}
        for name, comp in variants.items():
            res = evaluate(comp, s.dy_h[T], p.yields, engine.TENOR_SPEC[T], *thresholds(T), wins)
            for win, m in res.items():
                rows.append({"tenor": T, "variant": name, "window": win, **m, "today": float(comp.iloc[-1])})
    df = pd.DataFrame(rows)
    fmt = lambda ci: f"[{ci[0]:.2f}, {ci[1]:.2f}]"  # noqa: E731
    lines = ["# Ideas 1-3: results", "", f"Generated by `python -m ust_rv.backtest.ideas` on {pd.Timestamp.today():%Y-%m-%d}, "
             f"data through {p.market_date:%Y-%m-%d}. Specifications and adoption rule: `IDEAS_LOG.md`.", "",
             "| tenor | variant | window | IC | IC 95% CI | Sharpe | Sharpe 95% CI | hit rate | composite today |", "|---|---|---|---|---|---|---|---|---|"]
    lines += [f"| {r.tenor} | {r.variant} | {r.window} | {r.ic:.2f} | {fmt(r.ic_ci)} | {r.sharpe:.2f} | {fmt(r.sharpe_ci)} | {r.hit:.0%} | {r.today:+.2f} |"
              for r in df.itertuples()]
    avg = df.groupby(["variant", "window"])[["ic", "sharpe"]].mean().unstack("window")
    lines += ["", "## Tenor-averaged", "", "| variant | IC 2005+ | IC 2012+ | IC PIT>=90% | Sharpe 2005+ | Sharpe 2012+ | Sharpe PIT>=90% |", "|---|---|---|---|---|---|---|"]
    for v, r in avg.iterrows():
        lines.append(f"| {v} | " + " | ".join(f"{r[(m, w)]:.2f}" for m in ("ic", "sharpe") for w in ("2005+", "2012+", "PIT>=90%")) + " |")
    path = repo_path("runs") / "ideas_results.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines[-7:]))
    print(f"written: {path}")




# ---------- idea 5: forward-target model with the curve slope ----------

SLOPE_ROW_BOTH = {**SLOPE_ROW, "weight_2y": 1.0, "weight_10y": 1.0}


def with_slope_both(values: pd.DataFrame, lib: pd.DataFrame, yields: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Factor values and library with F7 added on both tenors (idea 5)."""
    v = values.assign(**{SLOPE_ID: slope_values(yields)})
    return v, pd.concat([lib, pd.DataFrame([SLOPE_ROW_BOTH], index=[SLOPE_ID]).reindex(columns=lib.columns)])


def theme_z(values: pd.DataFrame, lib: pd.DataFrame, tenor: str, available: set[str], zc: dict) -> pd.DataFrame:
    from ust_rv.scoring.composite import theme_pressure

    z = rolling_z(values[lib.index], zc["window"], zc["min_periods"], zc["clip"])
    w = lib[f"weight_{tenor}"].astype(float).where(lambda s: s.index.isin(list(available)), 0.0)
    return rolling_z(theme_pressure(z.mul(lib["sign"].astype(float), axis=1), w, lib["theme"]), zc["window"], zc["min_periods"], zc["clip"])


def ridge_forward(tz: pd.DataFrame, fwd_target: pd.Series, y: pd.Series, horizon: int, zc: dict) -> pd.Series:
    """Variant 5b: walk-forward non-negative ridge theme weights fit to the vol-scaled forward-adjusted move."""
    from ust_rv.backtest import engine, walkforward

    target = fwd_target / metrics.realized_vol_6m(y, horizon)
    std = lambda c: rolling_z(c, zc["window"], zc["min_periods"], zc["clip"])  # noqa: E731
    return walkforward.run(tz, target, horizon, engine.EMBARGO_DAYS, engine.MIN_TRAIN_DAYS, standardize=std).composite


def evaluate_forward(comp: pd.Series, dy: pd.Series, fwd: pd.Series, y: pd.DataFrame, tenor_spec: tuple, enter: float, exit_: float,
                     windows: dict[str, pd.DatetimeIndex]) -> dict:
    ycol, scol, s_years, years, _ = tenor_spec
    out = {}
    for name, idx in windows.items():
        c = comp.reindex(idx).dropna()
        if c.empty:
            continue
        rv = hysteresis(c, enter, exit_)
        yy = y.reindex(c.index)
        pnl = metrics.overlay_pnl(rv.fillna(0.0), yy[ycol], yy[scol], s_years, years, yy["ff"])
        frame = pd.concat([c.rename("c"), fwd.rename("d")], axis=1).dropna()
        out[name] = {"ic_fwd": metrics.ic(c, fwd),
                     "ic_fwd_ci": metrics.block_bootstrap(frame, lambda f: metrics.ic(f["c"], f["d"]), block=126, n_draws=300),
                     "ic_raw": metrics.ic(c, dy), "sharpe": metrics.sharpe(pnl),
                     "sharpe_ci": metrics.block_bootstrap(metrics.monthly(pnl).to_frame("pnl"),
                                                          lambda f: metrics._annualized_sharpe(f["pnl"]), block=6, n_draws=300),
                     "hit_fwd": metrics.hit_rate(rv, fwd)}
    return out


def main_idea5() -> None:
    import logging

    from ust_rv.backtest import engine
    from ust_rv.backtest.forward_target import forward_target
    from ust_rv.config import factors, repo_path, settings, thresholds
    from ust_rv.panel import build_panel
    from ust_rv.scoring.scorecard import compute_scores

    logging.basicConfig(level=logging.ERROR)
    p = build_panel()
    s = compute_scores(p)
    lib = pd.DataFrame(factors()).set_index("id")
    zc, h = settings()["zscore"], settings()["horizon_days"]
    available = {k for k, m in p.meta.items() if m["status"] in ("ok", "stale")}
    v5, lib5 = with_slope_both(p.values, lib, p.yields)
    rows = []
    for T in ("2y", "10y"):
        fwd = forward_target(p.yields, T, h)
        w = engine.windows(engine.pit_share(p, T))
        wins = {"2005+": w["2005+"], "2009+": w["2009+"], "2012+": w["2005+"][w["2005+"] >= "2012-01-01"], "PIT>=90%": w["PIT>=90%"]}
        variants = {
            "live": s.composite[T],
            "5a: hand + slope": composite(v5, lib5, s.theme_weights[T], T, available | {SLOPE_ID}, zc),
            "5b: ridge on forward target + slope": ridge_forward(theme_z(v5, lib5, T, available | {SLOPE_ID}, zc), fwd,
                                                                 p.yields[{"2y": "y2", "10y": "y10"}[T]], h, zc),
        }
        for name, comp in variants.items():
            for win, m in evaluate_forward(comp, s.dy_h[T], fwd, p.yields, engine.TENOR_SPEC[T], *thresholds(T), wins).items():
                rows.append({"tenor": T, "variant": name, "window": win, **m, "today": float(comp.dropna().iloc[-1])})
    df = pd.DataFrame(rows)
    ci = lambda c: f"[{c[0]:.2f}, {c[1]:.2f}]"  # noqa: E731
    lines = ["# Idea 5: forward-target model with the curve slope", "",
             f"Generated by `python -m ust_rv.backtest.ideas idea5` on {pd.Timestamp.today():%Y-%m-%d}, data through {p.market_date:%Y-%m-%d}. "
             "Specification and adoption rule: `IDEAS_LOG.md` idea 5. Sharpe is the overlay P&L including carry and roll (an excess-return measure).", "",
             "| tenor | variant | window | IC fwd | IC fwd 95% CI | IC raw | Sharpe | Sharpe 95% CI | hit vs fwd | composite today |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    lines += [f"| {r.tenor} | {r.variant} | {r.window} | {r.ic_fwd:.2f} | {ci(r.ic_fwd_ci)} | {r.ic_raw:.2f} | {r.sharpe:.2f} | {ci(r.sharpe_ci)} | "
              f"{r.hit_fwd:.0%} | {r.today:+.2f} |" for r in df.itertuples()]
    avg = df.groupby(["variant", "window"])[["ic_fwd", "sharpe"]].mean().unstack("window")
    lines += ["", "## Tenor-averaged", "", "| variant | " + " | ".join(f"IC fwd {w}" for w in wins) + " | " + " | ".join(f"Sharpe {w}" for w in wins) + " |",
              "|---|" + "---|" * (2 * len(wins))]
    for v, r in avg.iterrows():
        lines.append(f"| {v} | " + " | ".join(f"{r.get(('ic_fwd', w), float('nan')):.2f}" for w in wins) + " | "
                     + " | ".join(f"{r.get(('sharpe', w), float('nan')):.2f}" for w in wins) + " |")
    path = repo_path("runs") / "idea5_results.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    import sys

    main_idea5() if sys.argv[1:] == ["idea5"] else main()
