"""Idea 4 (IDEAS_LOG.md): evaluate the model against the 6m change versus the forward curve instead of the raw
6m yield change. Diagnostics only; nothing here changes the live model."""
import pandas as pd

from ust_rv.backtest import metrics

HORIZON_YEARS = 0.5


def forward_yield(curve: pd.DataFrame, n: float) -> pd.Series:
    """Yield on an n-year bond starting 6 months from now, from today's curve (par yields used as zero yields)."""
    long = {2.0: (curve["y2"] + curve["y3"]) / 2, 10.0: curve["y10"] + 0.05 * (curve["y20"] - curve["y10"])}[n]
    return ((n + HORIZON_YEARS) * long - HORIZON_YEARS * curve["y6m"]) / n


def forward_target(curve: pd.DataFrame, tenor: str, horizon_days: int) -> pd.Series:
    """Realized n-year yield in 6 months minus today's 6m-forward n-year yield, bp. NaN until realized."""
    n, col = {"2y": (2.0, "y2"), "10y": (10.0, "y10")}[tenor]
    return (curve[col].shift(-horizon_days) - forward_yield(curve, n)) * 100.0


def main() -> None:
    import logging

    from ust_rv.backtest import engine, ideas
    from ust_rv.config import factors, repo_path, settings
    from ust_rv.features.zscore import rolling_z
    from ust_rv.panel import build_panel
    from ust_rv.scoring.scorecard import compute_scores

    logging.basicConfig(level=logging.ERROR)
    p = build_panel()
    s = compute_scores(p)
    lib = pd.DataFrame(factors()).set_index("id")
    zc, h = settings()["zscore"], settings()["horizon_days"]
    curve = p.yields
    lines = ["# Idea 4: forward-adjusted target diagnostics", "",
             f"Generated by `python -m ust_rv.backtest.forward_target` on {pd.Timestamp.today():%Y-%m-%d}, data through {p.market_date:%Y-%m-%d}. "
             "raw = 6m change in the yield (the live target); fwd = realized yield in 6m minus today's 6m-forward yield. "
             "Specification: `IDEAS_LOG.md` idea 4.", ""]

    lines += ["## (a) Live composite against each target", "",
              "| tenor | window | IC raw | IC fwd | IC fwd 95% CI | hit raw | hit fwd | mean fwd-implied move, bp |", "|---|---|---|---|---|---|---|---|"]
    targets = {}
    for T in ("2y", "10y"):
        fwd = forward_target(curve, T, h)
        targets[T] = fwd
        n = {"2y": 2.0, "10y": 10.0}[T]
        implied = (forward_yield(curve, n) - curve[{"2y": "y2", "10y": "y10"}[T]]) * 100.0
        w = engine.windows(engine.pit_share(p, T))
        wins = {"2005+": w["2005+"], "2012+": w["2005+"][w["2005+"] >= "2012-01-01"], "PIT>=90%": w["PIT>=90%"]}
        comp, rv = s.composite[T], s.rv[T]
        for name, idx in wins.items():
            c = comp.reindex(idx)
            frame = pd.concat([c.rename("c"), fwd.rename("d")], axis=1).dropna()
            ci = metrics.block_bootstrap(frame, lambda f: metrics.ic(f["c"], f["d"]), block=126, n_draws=500)
            lines.append(f"| {T} | {name} | {metrics.ic(c, s.dy_h[T]):.2f} | {metrics.ic(c, fwd):.2f} | [{ci[0]:.2f}, {ci[1]:.2f}] | "
                         f"{metrics.hit_rate(rv.reindex(idx), s.dy_h[T]):.0%} | {metrics.hit_rate(rv.reindex(idx), fwd):.0%} | "
                         f"{implied.reindex(idx).mean():+.0f} |")
    lines.append("")

    lines += ["## (b) Factor IC since 2005 against each target", "",
              "| tenor | factor | sign | weight | IC raw | IC fwd | change |", "|---|---|---|---|---|---|---|"]
    available = {k for k, m in p.meta.items() if m["status"] in ("ok", "stale")}
    neg = {}
    for T in ("2y", "10y"):
        ids = [f for f in lib.index if lib.loc[f, f"weight_{T}"] > 0 and f in available]
        rows = []
        for f in ids:
            pr = s.pressure[f].loc["2005":]
            rows.append((f, metrics.ic(pr, s.dy_h[T]), metrics.ic(pr, targets[T])))
        neg[T] = (sum(r[1] < 0 for r in rows), sum(r[2] < 0 for r in rows), len(rows))
        for f, a, b in sorted(rows, key=lambda r: r[2] - r[1]):
            lines.append(f"| {T} | {f} {lib.loc[f, 'name']} | {int(lib.loc[f, 'sign']):+d} | {lib.loc[f, f'weight_{T}']:.1f} | {a:.2f} | {b:.2f} | {b - a:+.2f} |")
    lines += ["", "Weighted factors with negative IC since 2005: " +
              "; ".join(f"{T}: {a} of {n} against raw, {b} of {n} against fwd" for T, (a, b, n) in neg.items()), ""]

    slope_z = rolling_z(ideas.slope_values(p.yields), zc["window"], zc["min_periods"], zc["clip"]) * ideas.SLOPE_ROW["sign"]
    lines += ["## (c) Idea 1 slope factor (pressure) against each target, since 2005", "",
              "| tenor | IC raw | IC fwd |", "|---|---|---|"]
    for T in ("2y", "10y"):
        lines.append(f"| {T} | {metrics.ic(slope_z.loc['2005':], s.dy_h[T]):.2f} | {metrics.ic(slope_z.loc['2005':], targets[T]):.2f} |")
    path = repo_path("runs") / "forward_target.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"written: {path}")


if __name__ == "__main__":
    main()
