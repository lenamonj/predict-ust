"""Alternative ways to score factors (window, z vs percentile, level vs change), applied uniformly to all
factors, plus a selection-honest test of choosing among them in real time."""
from dataclasses import dataclass
from itertools import product

import numpy as np
import pandas as pd
from scipy.stats import norm

from ust_rv.backtest import metrics
from ust_rv.backtest.robustness import composite_from_pressure
from ust_rv.backtest.walkforward import january_refit_dates
from ust_rv.features.zscore import rolling_z
from ust_rv.scoring.decision import hysteresis

WINDOWS = {"1y": 252, "3y": 756, "5y": 1260, "10y": 2520}
SCALES = ("z", "pct")
FORMS = ("level", "chg3m", "blend")
CHANGE_DAYS = 63
CHANGE_SCALE_WINDOW = 2520
CLIP = 3.0


@dataclass(frozen=True)
class Scheme:
    window: str
    scale: str
    form: str

    @property
    def name(self) -> str:
        return f"{self.window} {self.scale} {self.form}"


ALL_SCHEMES = [Scheme(w, s, f) for w, s, f in product(WINDOWS, SCALES, FORMS)]
LIVE = Scheme("10y", "z", "level")


def percentile_score(x: pd.DataFrame, window: int) -> pd.DataFrame:
    """Trailing rank of today's value within the window, mapped to the normal scale (mid-rank, clipped)."""
    roll = x.rolling(window, min_periods=window // 2)
    n = roll.count()
    p = roll.rank(pct=True) - 0.5 / n
    return pd.DataFrame(norm.ppf(p.clip(1e-6, 1 - 1e-6)), index=x.index, columns=x.columns).where(p.notna()).clip(-CLIP, CLIP)


def score(values: pd.DataFrame, scheme: Scheme) -> pd.DataFrame:
    w = WINDOWS[scheme.window]
    level = rolling_z(values, w, w // 2, CLIP) if scheme.scale == "z" else percentile_score(values, w)
    if scheme.form == "level":
        return level
    change = level - level.shift(CHANGE_DAYS)
    change = (change / change.rolling(CHANGE_SCALE_WINDOW, min_periods=CHANGE_SCALE_WINDOW // 2).std()).clip(-CLIP, CLIP)
    return change if scheme.form == "chg3m" else (level + change) / 2


def composite(values: pd.DataFrame, lib: pd.DataFrame, theme_weights: pd.Series, tenor: str, available: set[str], scheme: Scheme, zc: dict) -> pd.Series:
    w = lib[f"weight_{tenor}"].astype(float).where(lambda s: s.index.isin(list(available)), 0.0)
    pressure = score(values[lib.index], scheme).mul(lib["sign"], axis=1)
    return composite_from_pressure(pressure, w, lib["theme"], theme_weights, zc)


def rv_and_pnl(comp: pd.Series, y: pd.DataFrame, tenor_spec: tuple, enter: float, exit_: float, start: str) -> tuple[pd.Series, pd.Series]:
    ycol, scol, s_years, years, _ = tenor_spec
    rv = hysteresis(comp.loc[start:], enter, exit_).fillna(0.0)
    yy = y.loc[start:]
    return rv, metrics.overlay_pnl(rv, yy[ycol], yy[scol], s_years, years, yy["ff"])


def nested_scheme_selection(pnl: pd.DataFrame, rv: pd.DataFrame, menu: list[str], first_year: int = 2012) -> tuple[pd.Series, pd.Series, dict]:
    """Each January, pick the scheme in `menu` with the best Sharpe on P&L realized before that January (since the
    start of `pnl`), and trade it for the year. Returns the chained P&L, chained RV and the picks."""
    idx = pnl.index
    years = [d for d in january_refit_dates(idx) if d.year >= first_year]
    bounds = years + [idx[-1] + pd.Timedelta(days=1)]
    out_pnl, out_rv, picks = [], [], {}
    for k, start in enumerate(years):
        hist = pnl.loc[: start - pd.Timedelta(days=1), menu]
        m = hist.resample("ME").sum()
        sharpe = m.mean() / m.std().replace(0, np.nan)
        choice = sharpe.idxmax()
        period = (idx >= start) & (idx < bounds[k + 1])
        out_pnl.append(pnl.loc[period, choice])
        out_rv.append(rv.loc[period, choice])
        picks[start.year] = choice
    return pd.concat(out_pnl), pd.concat(out_rv), picks


MENUS = {
    "all 24 schemes": [sc.name for sc in ALL_SCHEMES],
    "z level, 4 windows": [Scheme(w, "z", "level").name for w in WINDOWS],
    "10y, scale x form": [Scheme("10y", s, f).name for s in SCALES for f in FORMS],
}


def main() -> None:
    """Write the fixed-scheme comparison and the nested selection results to runs/normalization_review.md."""
    import logging

    from ust_rv.backtest import engine
    from ust_rv.config import factors, repo_path, settings, thresholds
    from ust_rv.panel import build_panel
    from ust_rv.scoring.scorecard import compute_scores

    logging.basicConfig(level=logging.ERROR)
    p = build_panel()
    s = compute_scores(p)
    lib = pd.DataFrame(factors()).set_index("id")
    zc = settings()["zscore"]
    available = {k for k, m in p.meta.items() if m["status"] in ("ok", "stale")}
    lines = [
        "# Normalization review: results",
        "",
        f"Generated by `python -m ust_rv.backtest.normalization` on {pd.Timestamp.today():%Y-%m-%d}, data through {p.market_date:%Y-%m-%d}. "
        "Each scheme scores every factor the same way; themes and the composite are then built exactly as in the live model, and the live "
        "thresholds are applied. 24 schemes x 2 tenors are compared, so the best fixed scheme in the first table is selected in-sample: "
        "read the nested table for the honest comparison. Analysis and decision: `NORMALIZATION_REVIEW_PLAN.md`.",
        "",
    ]
    nested_rows = []
    for T in ("2y", "10y"):
        pit = engine.windows(engine.pit_share(p, T))["PIT>=90%"]
        dy = s.dy_h[T]
        rows, pnls, rvs = [], {}, {}
        for sc in ALL_SCHEMES:
            c = composite(p.values, lib, s.theme_weights[T], T, available, sc, zc)
            r = {"scheme": sc.name, "first value": f"{c.first_valid_index():%Y-%m-%d}",
                 "IC 2005+": metrics.ic(c.loc["2005":], dy), "IC 2012+": metrics.ic(c.loc["2012":], dy), "IC PIT>=90%": metrics.ic(c.reindex(pit), dy)}
            for start in ("2005-01-01", "2012-01-01"):
                r[f"Sharpe {start[:4]}+"] = metrics.sharpe(rv_and_pnl(c, p.yields, engine.TENOR_SPEC[T], *thresholds(T), start)[1])
            rows.append(r)
            rvs[sc.name], pnls[sc.name] = rv_and_pnl(c, p.yields, engine.TENOR_SPEC[T], *thresholds(T), "2009-01-01")
        table = pd.DataFrame(rows).sort_values("Sharpe 2012+", ascending=False)
        lines += [f"## {T}: fixed schemes (sorted by Sharpe 2012+; live = 10y z level)", "",
                  "| " + " | ".join(table.columns) + " |", "|" + "---|" * len(table.columns)]
        lines += ["| " + " | ".join(v if isinstance(v, str) else f"{v:.2f}" for v in row) + " |" for row in table.itertuples(index=False)]
        lines.append("")
        pdf, rdf = pd.DataFrame(pnls), pd.DataFrame(rvs)
        nested_rows.append({"tenor": T, "menu": "static (live: 10y z level)", "Sharpe 2012+": metrics.sharpe(pdf[LIVE.name].loc["2012":]), "picks": ""})
        for mname, menu in MENUS.items():
            pnl, _, picks = nested_scheme_selection(pdf, rdf, menu)
            nested_rows.append({"tenor": T, "menu": mname, "Sharpe 2012+": metrics.sharpe(pnl),
                                "picks": "; ".join(f"{y}: {v}" for y, v in picks.items())})
    lines += ["## Selection-honest test: choose the scheme each January from P&L realized since 2009", "",
              "| tenor | menu | Sharpe 2012+ | picks by year |", "|---|---|---|---|"]
    lines += [f"| {r['tenor']} | {r['menu']} | {r['Sharpe 2012+']:.2f} | {r['picks']} |" for r in nested_rows]
    path = repo_path("runs") / "normalization_review.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"written: {path}")


if __name__ == "__main__":
    main()
